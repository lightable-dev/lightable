"""Summarises corpus coverage by entity type, DXF version and writer.

Usage: python3 tools/corpus_coverage.py tests/corpus > tests/corpus/COVERAGE.md

Reads group-code pairs directly (independent of lightable-dxf) and counts the
`0 <TYPE>` records in the ENTITIES and BLOCKS sections. File names follow
<drawing>__<writer>__<version>.dxf; other files count as "hand-written".
"""

import sys
from collections import Counter, defaultdict
from pathlib import Path

# What the lightable-dxf reader parses into typed entities (M2).
PARSED = {
    "LINE", "CIRCLE", "ARC", "LWPOLYLINE", "ELLIPSE", "POINT", "TEXT", "MTEXT", "INSERT",
    "ATTRIB", "ATTDEF", "DIMENSION", "SPLINE", "POLYLINE", "VERTEX", "SEQEND",
}
# Structural records inside BLOCKS/ENTITIES that are not drawing entities.
STRUCTURAL = {"BLOCK", "ENDBLK", "SECTION", "ENDSEC", "EOF"}
VERSIONS = ["R12", "R14", "R2000", "R2004", "R2007", "R2010", "R2013", "R2018"]


def entity_types(path):
    """Yields (section, type) for each record in ENTITIES and BLOCKS."""
    # Split on "\n" only: str.splitlines() also splits on \x85, \x1c etc.,
    # which appear inside some writers' values and would misalign the pairs.
    lines = [l.rstrip("\r") for l in path.read_bytes().decode("latin-1").split("\n")]
    section, expect_name = None, False
    for i in range(0, len(lines) - 1, 2):
        code, value = lines[i].strip(), lines[i + 1].strip()
        if code == "0" and value == "SECTION":
            expect_name = True
        elif expect_name and code == "2":
            section, expect_name = value, False
        elif code == "0" and value == "ENDSEC":
            section = None
        elif code == "0" and section in ("ENTITIES", "BLOCKS") and value not in STRUCTURAL:
            yield section, value


def main():
    corpus = Path(sys.argv[1])
    files = sorted(corpus.glob("*.dxf"))
    occurrences = Counter()
    in_files = defaultdict(set)
    writers = defaultdict(set)
    versions = defaultdict(set)
    matrix = Counter()
    for path in files:
        parts = path.stem.split("__")
        writer, version = (parts[1], parts[2]) if len(parts) == 3 else ("hand-written", "—")
        matrix[(writer, version)] += 1
        for _, kind in entity_types(path):
            occurrences[kind] += 1
            in_files[kind].add(path.name)
            writers[kind].add(writer)
            versions[kind].add(version)

    all_writers = sorted({w for w, _ in matrix}, key=lambda w: (w == "hand-written", w))
    out = ["# Corpus coverage", "",
           "Generated by `tools/corpus_coverage.py`; do not edit by hand.", "",
           f"{len(files)} files. Entity records counted in ENTITIES and BLOCKS sections.", "",
           "## Files by writer and version", "",
           "| Writer | " + " | ".join(VERSIONS + ["—"]) + " | Total |",
           "| --- | " + " | ".join("---" for _ in VERSIONS + ["—"]) + " | --- |"]
    for w in all_writers:
        row = [matrix[(w, v)] for v in VERSIONS + ["—"]]
        out.append(f"| {w} | " + " | ".join(str(n) if n else "·" for n in row) + f" | {sum(row)} |")
    out += ["", "## Entity types", "",
            "Parsed = read into a typed entity by lightable-dxf today; everything else is kept as `Unknown`.", "",
            "| Type | Parsed | Records | Files | Writers | Versions |",
            "| --- | --- | --- | --- | --- | --- |"]
    for kind, n in occurrences.most_common():
        vs = [v for v in VERSIONS if v in versions[kind]]
        out.append(f"| {kind} | {'yes' if kind in PARSED else ''} | {n} | {len(in_files[kind])} "
                   f"| {', '.join(sorted(writers[kind]))} | {', '.join(vs) or '—'} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
