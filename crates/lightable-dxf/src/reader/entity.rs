/// `LWPOLYLINE`: each `10` starts a vertex; `20`, `40`, `41`, `42` and `91`
/// that follow belong to it.
fn lwpolyline<'r, 'a>(
    rest: &Rest<'r, 'a>,
    extra: &mut Extra<'r, 'a>,
) -> Result<EntityKind, String> {
    let mut poly = LwPolyline {
        flags: 0,
        constant_width: None,
        elevation: 0.0,
        thickness: 0.0,
        extrusion: Z_AXIS,
        vertices: Vec::new(),
    };
    let mut count = None;
    let mut has_y = true;
    for &t in rest {
        let vertex = poly.vertices.last_mut();
        match (t.code, vertex) {
            (10, _) => {
                if !has_y {
                    return Err(format!(
                        "vertex {} has no y (group code 20)",
                        poly.vertices.len()
                    ));
                }
                poly.vertices.push(LwVertex {
                    x: float_of(t)?,
                    ..LwVertex::default()
                });
                has_y = false;
            }
            (20, Some(v)) if !has_y => {
                v.y = float_of(t)?;
                has_y = true;
            }
            (40, Some(v)) => v.start_width = float_of(t)?,
            (41, Some(v)) => v.end_width = float_of(t)?,
            (42, Some(v)) => v.bulge = float_of(t)?,
            (91, Some(v)) => v.id = Some(i32_of(t)?),
            (90, _) if count.is_none() => count = Some(int_of(t)?),
            (70, _) => poly.flags = i16_of(t)?,
            (43, _) => poly.constant_width = Some(float_of(t)?),
            (38, _) => poly.elevation = float_of(t)?,
            (39, _) => poly.thickness = float_of(t)?,
            (210, _) => poly.extrusion.x = float_of(t)?,
            (220, _) => poly.extrusion.y = float_of(t)?,
            (230, _) => poly.extrusion.z = float_of(t)?,
            (20 | 40 | 41 | 42 | 91, _) => {
                return Err(format!("group code {} outside a vertex", t.code));
            }
            _ => extra.push(t),
        }
    }
    if !has_y {
        return Err("last vertex has no y (group code 20)".into());
    }
    if let Some(n) = count
        && usize::try_from(n).ok() != Some(poly.vertices.len())
    {
        return Err(format!(
            "vertex count {n} (group code 90) but {} vertices",
            poly.vertices.len()
        ));
    }
    Ok(EntityKind::LwPolyline(poly))
}

fn ellipse<'r, 'a>(rest: &Rest<'r, 'a>, extra: &mut Extra<'r, 'a>) -> Result<EntityKind, String> {
    let f = Fields::new(rest, &[10, 20, 30, 11, 21, 31, 40, 41, 42, 210, 220, 230]);
    let ratio = f.require(40, "axis ratio")?;
    if ratio <= 0.0 {
        return Err(format!("axis ratio {ratio} is not positive"));
    }
    let ellipse = Ellipse {
        center: f.point(10, "centre")?,
        major_axis: f.point(11, "major axis")?,
        ratio,
        start_param: f.float_or(41, 0.0)?,
        end_param: f.float_or(42, std::f64::consts::TAU)?,
        extrusion: f.extrusion()?,
    };
    f.leftovers(extra);
    Ok(EntityKind::Ellipse(ellipse))
}

