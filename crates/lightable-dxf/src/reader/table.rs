//! Parsing symbol table entries and block headers.

use crate::model::{Block, Color, Handle};
use crate::table::{BlockRecord, DimStyle, Layer, Linetype, LinetypeElement, TextStyle};
use crate::tokenizer::Token;

use super::fields::{
    Fields, flag_of, float_of, handle_of, i16_of, int_of, invalid, lineweight_of, name_of,
    owned_in_order, split, true_color_of,
};

/// Handle and owner shared by every table entry.
#[derive(Default)]
struct Ids {
    handle: Option<Handle>,
    owner: Option<Handle>,
}

/// Splits an entry's pairs into ids, type-specific pairs and `extra`.
/// `handle_codes` lists the codes that hold the entry's handle (`5`, or
/// `105` for `DIMSTYLE`).
fn entry<'r, 'a>(
    body: &'r [Token<'a>],
    handle_codes: &[i16],
    extra: &mut Vec<&'r Token<'a>>,
) -> Result<(Ids, Vec<&'r Token<'a>>), String> {
    let mut ids = Ids::default();
    let (rest, error) = split(body, extra, |t| {
        match t.code {
            c if handle_codes.contains(&c) && ids.handle.is_none() => {
                ids.handle = Some(handle_of(t)?);
            }
            330 if ids.owner.is_none() => ids.owner = Some(handle_of(t)?),
            // Subclass markers are regenerated by the writer.
            100 => {}
            _ => return Ok(false),
        }
        Ok(true)
    });
    match error {
        Some(message) => Err(message),
        None => Ok((ids, rest)),
    }
}

fn required_name(f: &Fields<'_, '_, '_>) -> Result<String, String> {
    match f.token(2).map(name_of) {
        Some(name) if !name.is_empty() => Ok(name),
        _ => Err("missing name (group code 2)".into()),
    }
}

pub(super) fn layer(body: &[Token<'_>]) -> Result<Layer, String> {
    let mut extra = Vec::new();
    let (ids, rest) = entry(body, &[5], &mut extra)?;
    let f = Fields::new(&rest, &[2, 70, 62, 420, 6, 370, 290]);
    let mut layer = Layer::new(required_name(&f)?);
    layer.handle = ids.handle;
    layer.owner = ids.owner;
    layer.flags = f.int16_or(70, 0)?;
    if let Some(t) = f.token(62) {
        let value = int_of(t)?;
        layer.color = Color::from_aci(value.abs()).ok_or_else(|| invalid(t))?;
        layer.on = value >= 0;
    }
    if let Some(t) = f.token(420) {
        layer.color = true_color_of(t)?;
    }
    if let Some(t) = f.token(6) {
        layer.linetype = name_of(t);
    }
    if let Some(t) = f.token(370) {
        layer.lineweight = lineweight_of(t)?;
    }
    if let Some(t) = f.token(290) {
        layer.plot = flag_of(t)?;
    }
    f.leftovers(&mut extra);
    layer.extra = owned_in_order(extra);
    Ok(layer)
}

/// `LTYPE`: each `49` starts a pattern element; the `74`, `75`, `340`,
/// `46`, `50`, `44`, `45` and `9` pairs that follow belong to it.
pub(super) fn linetype(body: &[Token<'_>]) -> Result<Linetype, String> {
    let mut extra = Vec::new();
    let (ids, rest) = entry(body, &[5], &mut extra)?;
    let mut lt = Linetype {
        name: String::new(),
        handle: ids.handle,
        owner: ids.owner,
        flags: 0,
        description: String::new(),
        alignment: 65,
        pattern_length: 0.0,
        elements: Vec::new(),
        extra: Vec::new(),
    };
    let mut name = None;
    let mut count = None;
    for &t in &rest {
        let element = lt.elements.last_mut();
        match (t.code, element) {
            (49, _) => lt.elements.push(LinetypeElement {
                length: float_of(t)?,
                scale: 1.0,
                ..LinetypeElement::default()
            }),
            (74, Some(e)) => e.flags = i16_of(t)?,
            (75, Some(e)) => e.shape_number = i16_of(t)?,
            (340, Some(e)) => e.style = Some(handle_of(t)?),
            (46, Some(e)) => e.scale = float_of(t)?,
            (50, Some(e)) => e.rotation = float_of(t)?,
            (44, Some(e)) => e.offset.0 = float_of(t)?,
            (45, Some(e)) => e.offset.1 = float_of(t)?,
            (9, Some(e)) => e.text = Some(t.raw.to_owned()),
            (2, _) if name.is_none() => name = Some(name_of(t)),
            (70, _) => lt.flags = i16_of(t)?,
            (3, _) => lt.description = t.raw.to_owned(),
            (72, _) => lt.alignment = i16_of(t)?,
            (73, _) => count = Some(int_of(t)?),
            (40, _) => lt.pattern_length = float_of(t)?,
            _ => extra.push(t),
        }
    }
    lt.name = name
        .filter(|n| !n.is_empty())
        .ok_or("missing name (group code 2)")?;
    if let Some(n) = count
        && usize::try_from(n).ok() != Some(lt.elements.len())
    {
        return Err(format!(
            "element count {n} (group code 73) but {} elements",
            lt.elements.len()
        ));
    }
    lt.extra = owned_in_order(extra);
    Ok(lt)
}

pub(super) fn text_style(body: &[Token<'_>]) -> Result<TextStyle, String> {
    let mut extra = Vec::new();
    let (ids, rest) = entry(body, &[5], &mut extra)?;
    let f = Fields::new(&rest, &[2, 70, 40, 41, 50, 71, 42, 3, 4]);
    // Shape-file entries (flag 1) have an empty name, but the pair is there.
    let name = f
        .token(2)
        .map(name_of)
        .ok_or("missing name (group code 2)")?;
    let style = TextStyle {
        name,
        handle: ids.handle,
        owner: ids.owner,
        flags: f.int16_or(70, 0)?,
        height: f.float_or(40, 0.0)?,
        width_factor: f.float_or(41, 1.0)?,
        oblique: f.float_or(50, 0.0)?,
        generation_flags: f.int16_or(71, 0)?,
        last_height: f.float_or(42, 0.0)?,
        font: f.raw(3).unwrap_or_default().trim().to_owned(),
        big_font: f.raw(4).unwrap_or_default().trim().to_owned(),
        extra: Vec::new(),
    };
    f.leftovers(&mut extra);
    Ok(TextStyle {
        extra: owned_in_order(extra),
        ..style
    })
}

pub(super) fn dim_style(body: &[Token<'_>]) -> Result<DimStyle, String> {
    let mut extra = Vec::new();
    // DIMSTYLE keeps its handle in 105: group 5 is the DIMBLK variable
    // (the arrow block name), which R12 files use.
    let (ids, rest) = entry(body, &[105], &mut extra)?;
    let mut name = None;
    let mut flags = 0;
    let mut variables = Vec::with_capacity(rest.len());
    for &t in &rest {
        match t.code {
            2 if name.is_none() => name = Some(name_of(t)),
            70 => flags = i16_of(t)?,
            _ => variables.push(t.to_pair()),
        }
    }
    Ok(DimStyle {
        name: name
            .filter(|n| !n.is_empty())
            .ok_or("missing name (group code 2)")?,
        handle: ids.handle,
        owner: ids.owner,
        flags,
        variables,
        extra: owned_in_order(extra),
    })
}

pub(super) fn block_record(body: &[Token<'_>]) -> Result<BlockRecord, String> {
    let mut extra = Vec::new();
    let (ids, rest) = entry(body, &[5], &mut extra)?;
    let f = Fields::new(&rest, &[2, 340, 70, 280, 281]);
    let record = BlockRecord {
        name: required_name(&f)?,
        handle: ids.handle,
        owner: ids.owner,
        layout: f.token(340).map(handle_of).transpose()?,
        units: f.int16_or(70, 0)?,
        explodable: f.token(280).map(flag_of).transpose()?.unwrap_or(true),
        scalable: f.token(281).map(flag_of).transpose()?.unwrap_or(true),
        extra: Vec::new(),
    };
    f.leftovers(&mut extra);
    Ok(BlockRecord {
        extra: owned_in_order(extra),
        ..record
    })
}

/// The `BLOCK` record that opens a block definition (without its entities).
pub(super) fn block_header(body: &[Token<'_>]) -> Result<Block, String> {
    let mut extra = Vec::new();
    let mut layer = None;
    let mut ids = Ids::default();
    let (rest, error) = split(body, &mut extra, |t| {
        match t.code {
            5 if ids.handle.is_none() => ids.handle = Some(handle_of(t)?),
            330 if ids.owner.is_none() => ids.owner = Some(handle_of(t)?),
            8 => layer = Some(name_of(t)),
            100 => {}
            _ => return Ok(false),
        }
        Ok(true)
    });
    if let Some(message) = error {
        return Err(message);
    }
    let f = Fields::new(&rest, &[2, 3, 70, 10, 20, 30, 1, 4]);
    let mut block = Block::new(required_name(&f)?);
    block.handle = ids.handle;
    block.owner = ids.owner;
    if let Some(layer) = layer {
        block.layer = layer;
    }
    block.flags = f.int16_or(70, 0)?;
    block.base_point = f.optional_point(10, "base point")?.unwrap_or_default();
    block.xref_path = f.raw(1).unwrap_or_default().to_owned();
    block.description = f.raw(4).unwrap_or_default().to_owned();
    f.leftovers(&mut extra);
    // Group 3 repeats the name; keep it only if it says something else.
    if let Some(t) = f.token(3)
        && t.raw.trim() != block.name
    {
        extra.push(t);
    }
    block.extra = owned_in_order(extra);
    Ok(block)
}
